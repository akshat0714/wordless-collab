test("concept and fuzzy vectors recover novel jumbled misspellings", () => {
  const examples = [
    ["mony lef mi crd two tims", "duplicate_payment", "payment:synthetic-1842"],
    ["pakg nevr arivd", "delivery_late", "shipment:synthetic-4821"],
    ["pakg no com", "delivery_late", "shipment:synthetic-4821"],
    ["delvry nvr cme", "delivery_late", "shipment:synthetic-4821"],
    ["thing box no same as buy", "received_wrong_item", "order:synthetic-7304"],
    ["cant sing in acount", "cannot_sign_in", "account:synthetic-2259"],
  ];

  for (const [message, expectedChoice, expectedEvidence] of examples) {
    const result = assistMessage(message);
    assert.equal(result.outcome, "show_grounded_choices", message);
    assert.equal(result.choices[0].id, expectedChoice, message);
    assert.ok(result.choices[0].score >= 0.3, message);
    assert.equal(result.choices[0].evidenceId, expectedEvidence, message);
    assert.ok(result.choices.length <= 3, message);
    assert.equal(result.choices.at(-1).id, "something_else", message);
  }

  const query = conceptEngineInternals.conceptVector("pakg nevr arivd");
  const prototype = conceptEngineInternals.conceptVector("package never arrived");
  assert.ok(conceptEngineInternals.cosineSimilarity(query, prototype) > 0.7);
});

test("ambiguous support text offers a small evidence-grounded set", () => {
  const result = assistMessage("please help with the money and package on my order");

  assert.equal(result.outcome, "show_grounded_choices");
  assert.equal(result.selectionBasis, "ambiguous_message");
  assert.ok(result.choices.length >= 2 && result.choices.length <= 3);
  assert.ok(result.choices.filter((choice) => choice.kind === "grounded").every((choice) => choice.evidenceId));
  assert.equal(result.choices.at(-1).id, "something_else");
  assert.equal(new Set(result.choices.map((choice) => choice.id)).size, result.choices.length);
});

test("clear unrelated messages continue the ordinary chatbot", () => {
  const messages = [
    "I would like to update my mailing address",
    "I need to change my shipping address",
    "Can I order two blue shirts?",
    "Please close my account",
    "When are you open?",
  ];

  for (const message of messages) {
    const result = assistMessage(message);
    assert.equal(result.outcome, "continue_host_bot", message);
    assert.deepEqual(result.choices, [], message);
    assert.equal(result.selectionBasis, "no_supported_match", message);
  }
});

test("empty and illegible input share the context-ranked fallback", () => {
  const empty = assistMessage("");
  const illegible = assistMessage("zzz qrp blrg");

  for (const result of [empty, illegible]) {
    assert.equal(result.outcome, "show_grounded_choices");
    assert.equal(result.selectionBasis, "account_context_fallback");
    assert.equal(result.choices.length, 3);
    assert.equal(result.choices.at(-1).id, "something_else");
    assert.ok(result.choices.slice(0, 2).every((choice) => choice.evidenceId));
  }
  assert.deepEqual(
    empty.choices.map((choice) => choice.id),
    illegible.choices.map((choice) => choice.id),
  );
  assert.doesNotMatch(illegible.prompt, /illegible|gibberish|bad writing/i);
});

test("a short unclear cue gets compassionate account-context choices", () => {
  const result = assistMessage("need it agin");

  assert.equal(result.outcome, "show_grounded_choices");
  assert.equal(result.selectionBasis, "account_context_fallback");
  assert.equal(result.choices.length, 3);
  assert.equal(result.choices.at(-1).id, "something_else");
  assert.doesNotMatch(result.prompt, /illegible|gibberish|bad writing/i);
});
